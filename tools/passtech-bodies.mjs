// Writes passtech-bodies.json: the sanctioning bodies and disciplines PassTech offers (its rulesets),
// for fabricators to list what they build cages for. Run after PassTech adds or renames a body:
//   node tools/passtech-bodies.mjs [path to the PassTech repository, default ../safety-gear-check]
// It bundles PassTech's src/data with PassTech's own esbuild, then keeps only the names.
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { pathToFileURL } from "node:url";

const ROOT = resolve(new URL(".", import.meta.url).pathname.replace(/^\/(\w:)/, "$1"), "..");
const PASSTECH = resolve(process.argv[2] || join(ROOT, "..", "safety-gear-check"));
const dir = mkdtempSync(join(tmpdir(), "passtech-bodies-"));
const out = join(dir, "data.mjs");
const esbuild = join(PASSTECH, "node_modules", ".bin", process.platform === "win32" ? "esbuild.cmd" : "esbuild");
execFileSync(esbuild, [join(PASSTECH, "src", "data", "index.ts"), "--bundle", "--format=esm", "--platform=node", "--outfile=" + out,
  "--alias:@=" + join(PASSTECH, "src")], { stdio: "inherit", shell: process.platform === "win32" });
const { ALL_RULESETS } = await import(pathToFileURL(out).href);
const list = ALL_RULESETS.map((r) => ({ id: r.id, body: r.bodyId, bodyName: r.bodyName, discipline: r.disciplineName, group: r.disciplineGroup }))
  .sort((a, b) => a.bodyName.localeCompare(b.bodyName) || a.discipline.localeCompare(b.discipline));
const file = join(ROOT, "passtech-bodies.json");
const before = (() => { try { return readFileSync(file, "utf8"); } catch (e) { return ""; } })();
const text = JSON.stringify({ note: "Generated by tools/passtech-bodies.mjs from PassTech's rulesets -- don't edit.", rulesets: list }, null, 1) + "\n";
writeFileSync(file, text);
console.log((before === text ? "Unchanged: " : "Wrote ") + file + " (" + list.length + " rulesets, " + new Set(list.map((r) => r.body)).size + " bodies)");
