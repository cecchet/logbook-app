// Writes the migration that loads the built-in tech sheet templates
// (tech-sheets/templates/*.json) into the server's library (body_id null):
//   node tools/build-tech-sheet-seed.js [migration file name]
// Run it again after changing a template, as a new migration (default name:
// today's date) -- a changed template gets a new version, an unchanged one
// is left alone. Each file is checked against tech-sheets/FORMAT.md first.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const dir = path.join(ROOT, "tech-sheets", "templates");
const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
const out = path.join(ROOT, "supabase", "migrations", process.argv[2] || stamp + "_tech_sheet_library.sql");

const GEAR = new Set(["helmet", "balaclava", "hnr", "neck_collar", "firesuit", "gloves", "shoes", "socks", "undergarment", "arm_restraint",
  "seat", "belts_harness", "window_net", "fuel_cell", "fire_extinguisher", "fire_suppression", "window_breaker", "hood_pins",
  "spill_kit", "kill_switch", "tow_hook", "tow_rope", "emergency_triangle", "first_aid_kit", "parachute", "rollover_protection"]);
const FIELD_TYPES = new Set(["text", "number", "date", "choice", "multi"]);

function check(t, file) {
  const err = (m) => { throw new Error(file + ": " + m); };
  if (t.format !== 1) err("format must be 1");
  ["id", "bodyId", "title"].forEach((k) => { if (!t[k]) err("missing " + k); });
  const variants = new Set((t.variants || []).map((v) => v.id));
  const fields = (list, where) => (list || []).forEach((f) => {
    if (!f.id || !f.label) err(where + ": a field needs an id and a label");
    if (!FIELD_TYPES.has(f.type || "text")) err(where + ": field type " + f.type);
  });
  fields(t.header, "header");
  const ids = new Set();
  (t.sections || []).forEach((s) => {
    if (!s.id || !s.title) err("a section needs an id and a title");
    (s.items || []).forEach((i) => {
      if (!i.id || !i.label) err(s.id + ": an item needs an id and a label");
      if (ids.has(i.id)) err("item id " + i.id + " used twice");
      ids.add(i.id);
      if (i.checkedBy && !["team", "scrutineer"].includes(i.checkedBy)) err(i.id + ": checkedBy " + i.checkedBy);
      if (i.gear && !GEAR.has(i.gear)) err(i.id + ": unknown gear " + i.gear);
      (i.variants || []).forEach((v) => { if (!variants.has(v)) err(i.id + ": unknown variant " + v); });
      fields(i.fields, i.id);
    });
  });
  return ids.size;
}

const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const rows = files.map((f) => {
  const t = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  const n = check(t, f);
  console.log(f + ": " + t.title + " -- " + n + " items");
  return t;
});
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const sql = `-- GENERATED by tools/build-tech-sheet-seed.js from tech-sheets/templates --
-- the built-in tech sheet library (body_id null). A changed template gets a
-- new version; an unchanged one is left as it is.
` + rows.map((t) => `insert into tech_sheet_templates (body_id, key, title, definition)
values (null, ${q(t.id)}, ${q(t.title)}, ${q(JSON.stringify(t))}::jsonb)
on conflict ((coalesce(body_id, '')), key) do update set title = excluded.title, definition = excluded.definition,
  version = tech_sheet_templates.version + 1, updated_at = now()
where tech_sheet_templates.definition is distinct from excluded.definition;
`).join("\n");
fs.writeFileSync(out, sql);
console.log("Wrote " + path.relative(ROOT, out) + " (" + rows.length + " templates)");
